function interpolate(value, vars) {
  return value.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`)
}

export function translate(language, key, vars = {}) {
  const value = translations[language]?.[key] ?? translations.en[key] ?? key
  return interpolate(value, vars)
}

/**
 * Localizes backend text while keeping farmer-entered crop and market names intact.
 * The backend contract remains English and is deliberately not changed for this UI concern.
 */
export function localizeBackendText(language, message) {
  if (!message) return ''
  const t = (key, vars) => translate(language, key, vars)

  if (message === 'No market data is available for this crop to generate a recommendation.') {
    return t('noMarketData')
  }
  if (message.includes('Could not reach the recommendation engine') || message.includes('Could not connect to backend')) {
    return t('backendUnavailable')
  }
  if (message.includes('Could not connect to backend server')) {
    return t('backendUnavailable')
  }
  if (message.includes('No road-distance provider is configured')) {
    return t('routingNotConfigured')
  }
  if (message.includes('Affected markets:')) {
    return message
  }
  if (message.includes('could not be uniquely geocoded') || message.includes('Geocoding unavailable')) {
    return t('geocodingFailed')
  }
  if (message.includes('Verified farm origin unavailable')) {
    return t('geocodingFailed')
  }
  if (message.includes('Verified market destination unavailable')) {
    return t('geocodingFailed')
  }
  if (message.includes('No road route was found')) {
    return t('routeNotFound')
  }
  if (message.includes('Route lookup failed') || message.includes('No verified route')) {
    return t('routingFailed')
  }

  if (message.includes('No Agmarknet market records matched') || message.includes('No live market records matched')) {
    return language === 'kn'
      ? 'ಆಯ್ಕೆಮಾಡಿದ ಫಿಲ್ಟರ್‌ಗಳಿಗೆ ಹೊಂದಿಕೆಯಾಗುವ ಯಾವುದೇ ನೇರ ಮಾರುಕಟ್ಟೆ ದಾಖಲೆಗಳು ಲಭ್ಯವಿಲ್ಲ.'
      : message
  }
  if (message.includes('DATA_GOV_API_KEY is not set')) {
    return language === 'kn'
      ? 'ದ್ವಿತೀಯ ಮಾಹಿತಿಗಾಗಿ DATA_GOV_API_KEY ಕಾನ್ಫಿಗರ್ ಮಾಡಲಾಗಿಲ್ಲ.'
      : message
  }

  const although = message.match(
    /^Although (.+) offers a slightly higher market price \(₹([\d.]+)\/kg vs ₹([\d.]+)\/kg\), (.+) is recommended because its lower transportation cost gives an estimated ₹([\d,.-]+) higher net return for your ([\d,.]+) kg of (.+)\.$/,
  )
  if (although) {
    return t('explanationAlthough', {
      higherMarket: although[1],
      higherPrice: although[2],
      bestPrice: although[3],
      market: although[4],
      amount: although[5],
      quantity: although[6],
      crop: although[7],
    })
  }

  const recommendation = message.match(
    /^(.+) is recommended for your ([\d,.]+) kg of (.+) from (.+)\. It gives the highest estimated net return of ₹([\d,.]+) \(market price ₹([\d.]+)\/kg, transportation cost ₹([\d,.]+)\), which is ₹([\d,.-]+) higher than (.+)\.$/,
  )
  if (recommendation) {
    return t('explanationRecommended', {
      market: recommendation[1],
      quantity: recommendation[2],
      crop: recommendation[3],
      location: recommendation[4],
      net: recommendation[5],
      price: recommendation[6],
      transport: recommendation[7],
      amount: recommendation[8],
      runnerUp: recommendation[9],
    })
  }

  return language === 'kn' ? t('explanationFallback') : message
}

const STORAGE_KEY = 'farmprofit_language'

const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    if (typeof window !== 'undefined') {
      try {
        const saved = localStorage.getItem(STORAGE_KEY)
        if (saved === 'en' || saved === 'kn') return saved
      } catch {
        // ignore localStorage access issues
      }
    }
    return 'en'
  })

  const setLanguage = (lang) => {
    setLanguageState(lang)
    if (typeof window !== 'undefined') {
      try {
        localStorage.setItem(STORAGE_KEY, lang)
      } catch {
        // ignore localStorage write issues
      }
    }
  }

  const value = useMemo(
    () => ({ language, setLanguage, t: (key, vars) => translate(language, key, vars) }),
    [language],
  )
  return createElement(LanguageContext.Provider, { value }, children)
}

export function useLanguage() {
  return useContext(LanguageContext) || {
    language: 'en',
    setLanguage: () => {},
    t: (key, vars) => translate('en', key, vars),
  }
}
